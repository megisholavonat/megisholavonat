import ipaddress

from pydantic import field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    DEBUG: bool = False
    REDIS_HOST: str = "localhost"
    REDIS_PORT: int = 6379
    # Prefix for every Redis key and the task stream, so environments
    # sharing one Redis (prod/dev) do not overwrite each other
    REDIS_KEY: str = "mhav-local"
    SOCKS5_PROXY_HOST: str | None = None
    SOCKS5_PROXY_PORT: int | None = None
    SOCKS5_PROXY_USERNAME: str | None = None
    SOCKS5_PROXY_PASSWORD: str | None = None
    SOCKS5_PROXY_ENABLE: bool = False
    GRAPHQL_ENDPOINT: str = ""
    POSTHOG_KEY: str | None = None
    # Async SQLAlchemy URL. Plain postgres:// or postgresql:// URLs (as
    # generated by CloudNativePG) are rewritten to use the asyncpg driver.
    DATABASE_URL: str = "postgresql+asyncpg://mhav:mhav@localhost:5432/mhav"
    # Path to a vehicles-*.jsonl(.gz) snapshot file. When set, upstream is
    # never called and each refresh serves the next snapshot from the file.
    REPLAY_FILE: str | None = None
    # Raw stop_delay_observations partitions older than this many whole months
    # are dropped; delay_daily_agg is kept forever
    HISTORY_RETENTION_MONTHS: int = 13
    # Reverse proxies (comma-separated IPs or CIDRs, or "*") whose
    # X-Forwarded-For / X-Forwarded-Proto headers are trusted. The client IP is
    # the rightmost X-Forwarded-For entry that is not a trusted proxy. Empty
    # (the default) trusts no header and uses the TCP peer address.
    TRUSTED_PROXIES: str = ""
    # Header carrying the client IP as a single address, set by the edge in
    # front of the ingress (CF-Connecting-IP behind Cloudflare). Honoured only
    # when the TCP peer is in TRUSTED_PROXIES and the value is a valid IP;
    # otherwise the X-Forwarded-For handling above applies. Empty disables it.
    CLIENT_IP_HEADER: str = ""
    # Device registrations allowed per hour (fixed window)
    DEVICE_REGISTRATIONS_PER_IP_PER_HOUR: int = 5
    DEVICE_REGISTRATIONS_PER_HOUR: int = 500
    # Devices not seen for this many days are deleted with all their data
    DEVICE_IDLE_DAYS: int = 180

    # Caching Constants
    CACHE_DURATION: int = 15 * 60  # 15 minutes

    @field_validator("DATABASE_URL")
    @classmethod
    def _use_asyncpg(cls, v: str) -> str:
        for prefix in ("postgres://", "postgresql://"):
            if v.startswith(prefix):
                return "postgresql+asyncpg://" + v.removeprefix(prefix)
        return v

    @field_validator("TRUSTED_PROXIES")
    @classmethod
    def _valid_proxies(cls, v: str) -> str:
        for item in filter(None, (p.strip() for p in v.split(","))):
            if item != "*":
                ipaddress.ip_network(item, strict=False)
        return v

    @property
    def trusted_proxies(self) -> list[str]:
        return [p.strip() for p in self.TRUSTED_PROXIES.split(",") if p.strip()]

    model_config = SettingsConfigDict(
        env_file=".env", env_file_encoding="utf-8", extra="ignore"
    )


settings = Settings()
