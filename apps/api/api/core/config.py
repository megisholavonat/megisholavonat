from pydantic import field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    DEBUG: bool = False
    REDIS_HOST: str = "localhost"
    REDIS_PORT: int = 6379
    # Prefix for every Redis key and the task stream, so environments
    # sharing one Redis (prod/dev) do not overwrite each other
    REDIS_KEY: str = "mhav-local"
    SOCKS5_PROXY_HOST: str | None = None
    SOCKS5_PROXY_PORT: int | None = None
    SOCKS5_PROXY_USERNAME: str | None = None
    SOCKS5_PROXY_PASSWORD: str | None = None
    SOCKS5_PROXY_ENABLE: bool = False
    GRAPHQL_ENDPOINT: str = ""
    POSTHOG_KEY: str | None = None
    # Async SQLAlchemy URL. Plain postgres:// or postgresql:// URLs (as
    # generated by CloudNativePG) are rewritten to use the asyncpg driver.
    DATABASE_URL: str = "postgresql+asyncpg://mhav:mhav@localhost:5432/mhav"

    # Caching Constants
    CACHE_DURATION: int = 15 * 60  # 15 minutes

    @field_validator("DATABASE_URL")
    @classmethod
    def _use_asyncpg(cls, v: str) -> str:
        for prefix in ("postgres://", "postgresql://"):
            if v.startswith(prefix):
                return "postgresql+asyncpg://" + v.removeprefix(prefix)
        return v

    model_config = SettingsConfigDict(
        env_file=".env", env_file_encoding="utf-8", extra="ignore"
    )


settings = Settings()
