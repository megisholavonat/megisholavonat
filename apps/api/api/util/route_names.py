_DEC_ENTITY = re.compile(r"&#(\d+);")
_HEX_ENTITY = re.compile(r"&#[xX]([0-9a-fA-F]+);")
_TAG = re.compile(r"<[^>]+>")


def route_code(route_short_name: str | None) -> int | None:
    """Glyph code point of a route shortName, as getMavRouteCode does."""
    if not route_short_name:
        return None
    if m := _DEC_ENTITY.search(route_short_name):
        return int(m.group(1))
    if m := _HEX_ENTITY.search(route_short_name):
        return int(m.group(1), 16)
    for ch in _TAG.sub("", route_short_name).strip():
        if ord(ch) in MAV_ROUTE_MAP:
            return ord(ch)
    return None


def route_name(route_short_name: str | None) -> str | None:
    """Readable line name (S10, Z30, IC, ...), as getMavRouteName does."""
    if not route_short_name:
        return None
    code = route_code(route_short_name)
    if code is not None and code in MAV_ROUTE_MAP:
        return MAV_ROUTE_MAP[code]
    clean = _TAG.sub("", route_short_name).strip()
    if clean and not clean.startswith("&#"):
        return clean
    return None
